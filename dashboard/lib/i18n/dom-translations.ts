interface PatternMatcher {
  pattern: RegExp;
  replacement: string;
}

function escapeRegex(text: string) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function templateToRegex(template: string) {
  // Erst alles escapen, dann die (escapten) Platzhalter zu
  // Fanggruppen machen — so kann kein Template-Inhalt die Regex
  // umbiegen.
  return new RegExp(
    "^" + escapeRegex(template).replace(/\\\{(\d+)\\\}/g, "(.+?)") + "$",
  );
}

function templateToReplacement(template: string) {
  return template.replace(/\{(\d+)\}/g, "$$$1");
}

function buildPatternMatchers(language: Language): PatternMatcher[] {
  return patternPairs.map(([de, en]) => {
    const source = language === "de" ? en : de;
    const target = language === "de" ? de : en;
    return {
      pattern: templateToRegex(normalise(source)),
      replacement: templateToReplacement(target),
    };
  });
}

function normalise(text: string) {
  return text.replace(/\s+/g, " ").trim();
}

function preserveWhitespace(original: string, translated: string) {
  const leading = original.match(/^\s*/)?.[0] ?? "";
  const trailing = original.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function buildMap(language: Language) {
  const map = new Map<string, string>();
  for (const [de, en] of phrasePairs) {
    if (language === "de") {
      map.set(normalise(en), de);
    } else {
      map.set(normalise(de), en);
    }
  }
  return map;
}

function buildTranslator(language: Language) {
  return {
    map: buildMap(language),
    patterns: buildPatternMatchers(language),
  };
}

function translateValue(
  value: string,
  map: Map<string, string>,
  patterns: PatternMatcher[],
) {
  const key = normalise(value);
  if (!key) return value;
  const translated = map.get(key);
  if (translated) return preserveWhitespace(value, translated);
  // Kein exakter Treffer — dann die Vorlagen probieren. Die laufen auf
  // dem normalisierten Text, damit Zeilenumbrueche in Bestaetigungen
  // nicht zum Match killer werden.
  for (const { pattern, replacement } of patterns) {
    if (pattern.test(key)) {
      return preserveWhitespace(value, key.replace(pattern, replacement));
    }
  }
  return value;
}

function shouldSkipNode(node: Node) {
  const parent = node.parentElement;
  if (!parent) return true;
  if (parent.closest("script,style,noscript,code,pre,textarea,[data-no-translate]")) return true;
  return false;
}

export function translateDashboardDom(language: Language, root: ParentNode = document) {
  if (typeof document === "undefined") return;
  const { map, patterns } = buildTranslator(language);

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (shouldSkipNode(node)) return NodeFilter.FILTER_REJECT;
      return normalise(node.textContent || "") ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    },
  });

  const textNodes: Text[] = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode as Text);
  }

  for (const node of textNodes) {
    const current = node.textContent || "";
    const translated = translateValue(current, map, patterns);
    if (translated !== current) node.textContent = translated;
  }

  const selector = "input[placeholder], textarea[placeholder], [title], [aria-label]";
  root.querySelectorAll?.(selector).forEach((element) => {
    for (const attr of ["placeholder", "title", "aria-label"]) {
      const value = element.getAttribute(attr);
      if (!value) continue;
      const translated = translateValue(value, map, patterns);
      if (translated !== value) element.setAttribute(attr, translated);
    }
  });
}
